#!/usr/bin/env python3
"""Generates bsp/startup.c (vector table + Reset_Handler) from the CMSIS IRQn_Type enum.
Run once; the generated file is committed. Usage: python3 tools/gen_startup.py"""
import re, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
hdr = (root / "third_party/cmsis_device_f4/stm32f407xx.h").read_text()
d = {int(m.group(2)): m.group(1) for m in re.finditer(r'^\s*(\w+)_IRQn\s*=\s*(\d+)\s*,?', hdr, re.M) if int(m.group(2)) >= 0}
N = max(d) + 1
decl = "\n".join(f"void {n}_IRQHandler(void) WEAK_ALIAS;" for _, n in sorted(d.items()))
tbl = "\n".join((f"    {d[i]}_IRQHandler," if i in d else f"    0,  /* IRQ {i}: reserved on STM32F407 */") for i in range(N))
src = f'''/* startup.c - GENERATED by tools/gen_startup.py. Reset handler + full STM32F407 vector table
 * ({N} device IRQs), written from scratch. IRQ order comes from the CMSIS IRQn_Type enum.
 * Shared by bootloader, application and CAN node. */
#include <stdint.h>
#include "stm32f4xx.h"
#include "bsp.h"

extern uint32_t _sidata, _sdata, _edata, _sbss, _ebss, _estack;
extern int main(void);

typedef void (*isr_t)(void);

void Default_Handler(void);
#define WEAK_ALIAS __attribute__((weak, alias("Default_Handler")))

void Reset_Handler(void);
void NMI_Handler(void)        WEAK_ALIAS;
void HardFault_Handler(void)  WEAK_ALIAS;
void MemManage_Handler(void)  WEAK_ALIAS;
void BusFault_Handler(void)   WEAK_ALIAS;
void UsageFault_Handler(void) WEAK_ALIAS;
void SVC_Handler(void)        WEAK_ALIAS;
void DebugMon_Handler(void)   WEAK_ALIAS;
void PendSV_Handler(void)     WEAK_ALIAS;
void SysTick_Handler(void)    WEAK_ALIAS;
{decl}

/* Unhandled interrupt: remember which one, then spin (the watchdog resets us if it is running). */
volatile uint32_t g_unhandled_irq = 0xFFFFFFFFu;
void Default_Handler(void)
{{
    g_unhandled_irq = (SCB->ICSR & SCB_ICSR_VECTACTIVE_Msk);
    for (;;) {{ }}
}}

/* .isr_vector is placed first in the image (512-byte aligned) by the linker script. */
__attribute__((section(".isr_vector"), used))
const isr_t g_vector_table[16 + {N}] = {{
    (isr_t)&_estack,
    Reset_Handler,
    NMI_Handler, HardFault_Handler, MemManage_Handler, BusFault_Handler, UsageFault_Handler,
    0, 0, 0, 0,
    SVC_Handler, DebugMon_Handler, 0, PendSV_Handler, SysTick_Handler,
{tbl}
}};

void Reset_Handler(void)
{{
    SCB->VTOR = (uint32_t)g_vector_table;          /* vector table lives wherever this image was linked */
    const uint32_t *src = &_sidata;
    for (uint32_t *dst = &_sdata; dst < &_edata; ) {{ *dst++ = *src++; }}
    for (uint32_t *dst = &_sbss; dst < &_ebss; ) {{ *dst++ = 0u; }}
    bsp_stack_paint();                              /* canary for stack high-water measurement */
    SCB->CPACR |= (0xFu << 20);                     /* FPU full access before any float code */
    __DSB(); __ISB();
    (void)main();
    for (;;) {{ }}
}}
'''
(root / "bsp/startup.c").write_text(src)
print("wrote bsp/startup.c with", N, "IRQ slots")
