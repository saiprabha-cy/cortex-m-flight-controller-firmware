#!/usr/bin/env python3
"""Generates an Ed25519 DEV signing key and the matching bootloader public-key header.
  keys/dev_private.key   32-byte seed, hex   (NEVER commit a production key; this one is for the demo)
  keys/dev_public.bin    32 raw bytes
  bootloader/inc/pubkey.h
Usage: python3 tools/keygen.py [--force]"""
import argparse, os, pathlib
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey
from cryptography.hazmat.primitives import serialization

root = pathlib.Path(__file__).resolve().parent.parent
ap = argparse.ArgumentParser(); ap.add_argument("--force", action="store_true"); a = ap.parse_args()
keys = root / "keys"; keys.mkdir(exist_ok=True)
priv_path = keys / "dev_private.key"
if priv_path.exists() and not a.force:
    seed = bytes.fromhex(priv_path.read_text().strip()); print("keeping existing", priv_path)
else:
    seed = os.urandom(32); priv_path.write_text(seed.hex() + "\n"); print("generated", priv_path)
sk = Ed25519PrivateKey.from_private_bytes(seed)
pk = sk.public_key().public_bytes(serialization.Encoding.Raw, serialization.PublicFormat.Raw)
(keys / "dev_public.bin").write_bytes(pk)
body = ",".join(f"0x{b:02x}" for b in pk)
(root / "bootloader/inc").mkdir(parents=True, exist_ok=True)
(root / "bootloader/inc/pubkey.h").write_text(
    "/* GENERATED by tools/keygen.py - Ed25519 public key trusted by the bootloader */\n"
    "#ifndef PUBKEY_H\n#define PUBKEY_H\n#include <stdint.h>\n"
    f"static const uint8_t g_fw_pubkey[32] = {{{body}}};\n#endif\n")
print("wrote keys/dev_public.bin and bootloader/inc/pubkey.h")
